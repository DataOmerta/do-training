let currentLang = 'en';

function t(key) { return (I18N[currentLang] && I18N[currentLang][key]) || I18N['en'][key] || key; }

async function detectLanguage() {
  // Admin always stays English
  if (location.hash === '#admin' || sessionStorage.getItem('admin_auth') === '1') { setLang('en'); return; }
  const saved = localStorage.getItem('do_lang');
  if (saved) { setLang(saved); return; }
  try {
    const r = await fetch('https://ipapi.co/json/', { signal: AbortSignal.timeout(3000) });
    const d = await r.json();
    if (d.country_code === 'GR') { setLang('el'); return; }
  } catch(e) {}
  setLang('en');
}

function setLang(lang) {
  if (!I18N[lang]) lang = 'en';
  currentLang = lang;
  localStorage.setItem('do_lang', lang);
  document.documentElement.lang = lang;
  applyTranslations();
  updateLangSelector();
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = val;
    else el.textContent = val;
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
}

function updateLangSelector() {
  const sel = document.getElementById('lang-selector');
  if (sel) sel.value = currentLang;
}
